#!/usr/bin/env python3
"""Compare dual-rail makespan against a same-run sequential estimate.

Reads STAGE19 logs generated by Webots. The theoretical sequential estimate is
not an independent single-rail benchmark or industrial throughput guarantee.
"""
from pathlib import Path
import csv

ROOT=Path(__file__).resolve().parents[1]

def read_side(side):
    name=f'stage21_{side}_rail_stations.csv'
    path=ROOT/'logs'/side/name
    if not path.exists():return None
    with path.open(newline='') as fp:rows=list(csv.DictReader(fp))
    passed=[r for r in rows if r['status']=='PASS']
    return {
        'station_count':len(passed),
        'last_pass_time_s':float(passed[-1]['time_s']) if passed else None,
        'expected_count': 3 if len(passed)==3 else 1,
        'path':str(path),
    }

def main():
    near=read_side('near');far=read_side('far')
    if near is None or far is None:
        print('Missing one or both Stage 21 rail station CSVs. Run a world in Webots first.')
        return 1
    for label,v in [('near',near),('far',far)]:
        print(f'{label.upper():5} {v["station_count"]} stations passed; last pass t={v["last_pass_time_s"]} s')
    if near['last_pass_time_s'] is None or far['last_pass_time_s'] is None:
        print('One side has not completed any rail station; cannot estimate speedup.')
        return 2
    # Completion times are simulation-time since both rails start in one world.
    # Do not treat this as field-measured production throughput.
    dual=max(near['last_pass_time_s'],far['last_pass_time_s'])
    sequential=near['last_pass_time_s']+far['last_pass_time_s']
    print(f'Dual-run simulated completion: {dual:.2f} s')
    print(f'Ideal sequential estimate from same-run side times: {sequential:.2f} s')
    print(f'Estimated side-cycle speedup: {sequential/dual:.2f}x')
    print('NOT an independently measured sequential baseline or industrial throughput.')
    return 0

if __name__=='__main__':raise SystemExit(main())
